#!/usr/bin/env bash

# Build the community-scripts copy of Bannarr from this repository's bannarr.sh.
#
# Usage: scripts/build-devscripts.sh [output-dir]      (default: dist/devscripts)
#
# Writes, laid out like the DevScripts repository so they can be copied into a fork as-is:
#   <output-dir>/tools/addon/bannarr.sh   the add-on, in community-scripts' format
#   <output-dir>/PR_DESCRIPTION.md        a pre-filled pull request description
#
# This repository's bannarr.sh stays the single source. Never edit the output; change
# bannarr.sh and run this again. The rules applied here are listed in docs/DEVELOPMENT.md
# under "Submitting to community-scripts".

set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
src="$root/bannarr.sh"
out=${1:-"$root/dist/devscripts"}
dest="$out/tools/addon/bannarr.sh"
repo_url="https://github.com/rpesta/bannarr"

# Their header format: Copyright line, "Author: Name (GitHubUsername)", their license, and
# Source pointing at the project the add-on comes from.
export CS_HEADER="# Copyright (c) 2021-2026 community-scripts ORG
# Author: Ryan Pesta (rpesta)
# License: MIT | https://github.com/community-scripts/ProxmoxVE/raw/main/LICENSE
# Source: $repo_url"

# The two source lines from their add-on template, tools/addon/_template.sh
export CS_CORE='source <(curl -fsSL "${COMMUNITY_SCRIPTS_CORE_URL:-https://raw.githubusercontent.com/community-scripts/core/main}/core/core.func")
source <(curl -fsSL "${COMMUNITY_SCRIPTS_CORE_URL:-https://raw.githubusercontent.com/community-scripts/core/main}/lib/tools.func")'
export CS_DOCS="$repo_url/blob/main/docs/DEVELOPMENT.md"

mkdir -p "$(dirname "$dest")"

# 1. Replace this repo's 4-line header with theirs.
# 2. Replace the marked devscripts-core block with their source lines.
# 3. Point the docs/DEVELOPMENT.md reference at this repository, since their repo has no such file.
awk '
  !header && /^# Copyright \(c\)/ { print ENVIRON["CS_HEADER"]; header = 1; skip = 3; next }
  skip > 0 { skip--; next }
  /^# >>> devscripts-core$/ { print ENVIRON["CS_CORE"]; print ""; block = 1; next }
  /^# <<< devscripts-core$/ { block = 0; next }
  block { next }
  { gsub("docs/DEVELOPMENT\\.md", ENVIRON["CS_DOCS"]); print }
' "$src" >"$dest"
chmod 755 "$dest"

# Check the result against their rules, so a change to bannarr.sh can't quietly break them.
fail=0
check() {
  if eval "$2"; then
    printf '  ok    %s\n' "$1"
  else
    printf '  FAIL  %s\n' "$1"
    fail=1
  fi
}
echo "Checking $dest"
check "bash syntax" "bash -n '$dest'"
check "community-scripts header" "sed -n 3p '$dest' | grep -q '^# Copyright (c) 2021-2026 community-scripts ORG$'"
check "author in Name (GitHubUsername) form" "grep -q '^# Author: Ryan Pesta (rpesta)$' '$dest'"
check "no license link to this repo" "! grep -q 'rpesta/bannarr/raw/main/LICENSE' '$dest'"
check "core.func and tools.func sourced" "[ \$(grep -c 'community-scripts/core/main' '$dest') -eq 2 ]"
check "build markers removed" "! grep -q 'devscripts-core' '$dest'"
check "APP_TYPE is addon" "grep -q '^APP_TYPE=\"addon\"$' '$dest'"
check "messages name the app (no \$APP)" "! grep -Eq 'msg_[a-z]+ \"[^\"]*\\\$\\{?APP' '$dest'"
check "no msg_info calls (each needs a closing msg_ok)" "! grep -v '^[[:space:]]*#' '$dest' | grep -q 'msg_info'"
check "no decorative comment banners" "! grep -Eq '^# *[-=#]{10,}' '$dest'"
check "no TODO notes" "! grep -q 'TODO' '$dest'"
check "installs no packages" "! grep -Eq '(apt|apt-get|apk|dnf|yum|zypper|pacman) +(install|add|-S)' '$dest'"
check "LF line endings" "! grep -q \$'\\r' '$dest'"

cat >"$out/PR_DESCRIPTION.md" <<EOF
<!-- Generated by scripts/build-devscripts.sh in $repo_url. Fill in every "TODO" before opening the PR. -->

## ✍️ Description

**Bannarr** is an add-on for designing the SSH login banner of an existing container or VM.
It runs inside the guest and shows a live preview while you choose ASCII art, which system
details appear, and their layout and colors. It can always put the original banner back.

- **Leaves the original banner intact:** Bannarr writes its own \`/etc/profile.d/00_bannarr.sh\`.
  It switches off \`00_lxc-details.sh\` by renaming it to \`00_lxc-details.sh.bannarr-disabled\`,
  so the file is never edited or deleted.
- **Keeps your credit if the user wants it:** on first run it reads the original banner's
  title ("<App> LXC Container") and the "Provided by: community-scripts ORG" line, and asks
  whether to keep each one. Both default to yes.
- **Optionally hides the \`/etc/motd\` copy:** it offers to hide the plain title-and-OS copy
  that \`motd_ssh\` writes there. This uses Bannarr's reversible quiet mode, which records
  every change.
- **Undo:** \`--revert\` restores the original banner and \`/etc/motd\` exactly, and
  \`--uninstall\` also removes Bannarr's settings.
- **No dependencies:** it installs no packages, needs no special fonts, and works without a
  UTF-8 locale.

Upstream project and full documentation: $repo_url. This file is generated from it with
\`scripts/build-devscripts.sh\`.

**AI assistance:** written with Claude (model: Claude Opus 5.5, reasoning level: TODO), then
reviewed against DevScripts \`AGENTS.md\` and \`.github/agents/pve-script-creator.agent.md\`.

### Rules that can't be followed exactly

- **Own functions.** It's an add-on, and the add-on template defines its own functions as well.
  The "only \`update_script()\`" rule applies to \`ct/\` and \`install/\` scripts.
- **\`core.func\` / \`tools.func\` at login.** The add-on sources both, as the template does.
  The banner it installs runs at every login in a plain POSIX \`sh\` (dash or busybox ash), so
  that file is self-contained by design.
- **No \`set -Eeuo pipefail\`.** The interactive menus rely on tests that return non-zero by
  design, and the add-on template doesn't set it either. Happy to change this if you'd prefer.
- **No telemetry hook**, matching the add-on template.
- **Website listing:** add-ons have no \`json/\` file in DevScripts. How would you like Bannarr
  listed?

## 🔗 Related Issue

Fixes # TODO (or remove)

