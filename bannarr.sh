# Print every BN_* variable as sh assignments. Used for bannarr.conf and embedded at the
# top of the generated profile script, so the banner needs no external files at login.
write_conf() {
  local v
  echo "# Bannarr configuration - edit with Bannarr, not by hand"
  for v in $(compgen -v BN_); do printf '%s=%s\n' "$v" "$(sq "${!v}")"; done
}

# Load settings from bannarr.conf (or defaults) and the art. Art drawn in the built-in font
# ("hostname", or "text" from the generator) is redrawn on every load, so it follows hostname
# changes; any other art comes from banner.txt. ART_LINES always holds the unscaled art.
load_state() {
  local v dir=${1:-$CONF_DIR}
  if [[ -f $dir/bannarr.conf && -O $dir/bannarr.conf ]]; then
    for v in $(compgen -v BN_); do unset "$v"; done
    # shellcheck disable=SC1090
    . "$dir/bannarr.conf"
  else
    set_defaults
  fi
  ART_LINES=()
  case ${BN_ART_SRC:-hostname} in
    hostname) preset_art hostname ;;
    text) block_text "${BN_ART_TEXT:-$(hn)}" ;;
    *) [[ -f $dir/banner.txt ]] && mapfile -t ART_LINES <"$dir/banner.txt" ;;
  esac
}

# Print the complete profile script: settings + renderer + art heredoc + call to _bn_show,
# all inside "if ...; then ( ... ); fi". The subshell keeps everything out of the login
# shell; [ -t 1 ] keeps non-interactive sessions (scp, rsync, ssh host cmd) silent; and the
# exported BANNARR_SHOWN stops the banner repeating in nested shells, tmux and screen
# (RHEL-likes also source profile.d from /etc/bashrc for every interactive shell).
# $1 = "preview" drops just that first check: the editor captures the preview's output, which
# is not a terminal, so the real check would print nothing. Everything else is identical.
build_profile() {
  echo "# $MARKER - re-run Bannarr to change. Settings: $CONF_FILE"
  if [[ ${1:-} == preview ]]; then
    echo 'if true; then ('
  else
    echo 'if [ -t 1 ] && [ -z "${BANNARR_SHOWN:-}" ]; then ('
  fi
  write_conf
  emit_renderer
  echo '_bn_art() {'
  echo "cat <<'__BANNARR_ART__'"
  art_out
  echo '__BANNARR_ART__'
  echo '}'
  echo '_bn_show'
  echo '); fi'
  echo 'BANNARR_SHOWN=1; export BANNARR_SHOWN'
}

