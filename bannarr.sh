# Renderer: POSIX sh embedded verbatim into the profile script. Also eval'd into
# this bash process so the TUI reuses the same labels and colors.
emit_renderer() {
  cat <<'__BANNARR_RENDERER__'
# Print the ANSI escape for a color spec: a name (red, gray...), "b"+name for bold,
# a 256-color number (0-255), or ''/none for no color.
_bn_c() {
  case "$1" in
    ''|none|default) ;;
    black) printf '\033[30m' ;;
    red) printf '\033[31m' ;;
    green) printf '\033[32m' ;;
    yellow) printf '\033[33m' ;;
    blue) printf '\033[34m' ;;
    magenta) printf '\033[35m' ;;
    cyan) printf '\033[36m' ;;
    white) printf '\033[37m' ;;
    gray|grey) printf '\033[90m' ;;
    bold) printf '\033[1m' ;;
    b?*) printf '\033[1m'; _bn_c "${1#b}" ;;
    *[!0-9]*) ;;
    *) printf '\033[38;5;%sm' "$1" ;;
  esac
}
# Print the threshold color for a usage percentage: green <60, yellow <85, red otherwise.
_bn_thc() {
  if [ "$1" -ge 85 ]; then _bn_c red; elif [ "$1" -ge 60 ]; then _bn_c yellow; else _bn_c green; fi
}
# Set _l to the display label for an item key. Order: per-item override BN_L_<key>,
# then the built-in default. For mnt:<path> pseudo-keys the label is the path.
_bn_label() {
  case "$1" in mnt:*) _l=${1#mnt:}; return 0 ;; esac
  eval "_l=\${BN_L_$1:-}"
  [ -n "$_l" ] && return 0
  case "$1" in
    hostname) _l='Hostname' ;; fqdn) _l='FQDN' ;; ip) _l='IPv4' ;; ipv6) _l='IPv6' ;;
    os) _l='OS' ;; kernel) _l='Kernel' ;; arch) _l='Arch' ;; uptime) _l='Uptime' ;;
    load) _l='Load' ;; cpu) _l='CPU' ;; cpu_model) _l='CPU Model' ;; cores) _l='Cores' ;;
    memory) _l='Memory' ;; swap) _l='Swap' ;; disk) _l='Disk (/)' ;; mounts) _l='Mounts' ;;
    procs) _l='Processes' ;; users) _l='Users' ;; date) _l='Date' ;; *) _l=$1 ;;
  esac
}
# Set _ic to the icon for an item key: per-item override BN_I_<key>, else the glyph
# from the active set in BN_ICONS (off | unicode | emoji). Empty means no icon. Both sets
# render in stock terminals and fonts, so the banner needs nothing installed.
_bn_icon() {
  eval "_ic=\${BN_I_$1:-}"
  [ -n "$_ic" ] && return 0
  case "$BN_ICONS" in
    unicode)
      case "$1" in
        # Only symbols from the original PC character set (code page 437), which practically
        # every terminal font includes; rarer ones like ▣ ⇄ ◫ showed as "?" boxes in testing
        hostname|fqdn) _ic='⌂' ;; ip|ipv6) _ic='↔' ;; os) _ic='♦' ;; kernel) _ic='▲' ;; arch) _ic='►' ;;
        uptime) _ic='↑' ;; load) _ic='≈' ;; cpu|cpu_model) _ic='■' ;; cores) _ic='∙' ;; memory) _ic='▬' ;;
        swap) _ic='↕' ;; disk|mounts) _ic='◘' ;; procs) _ic='≡' ;; users) _ic='☺' ;; date) _ic='○' ;;
      esac ;;
    emoji)
      case "$1" in
        hostname) _ic='🏠' ;; fqdn) _ic='🌐' ;; ip|ipv6) _ic='📡' ;; os) _ic='🐧' ;; kernel) _ic='🧬' ;;
        arch) _ic='🧩' ;; uptime) _ic='⏳' ;; load) _ic='📈' ;; cpu) _ic='🧠' ;; cpu_model) _ic='🔧' ;;
        cores) _ic='🔢' ;; memory) _ic='💾' ;; swap) _ic='🔁' ;; disk) _ic='💽' ;; mounts) _ic='📂' ;;
        procs) _ic='📋' ;; users) _ic='👥' ;; date) _ic='📅' ;;
      esac ;;
  esac
}
# Print every real mounted directory, one per line, from /proc/mounts. Skips pseudo
# filesystems (proc, tmpfs, cgroup, lxcfs...), /proc /sys /dev /run, and the
# single-file bind mounts LXC adds (/etc/hosts etc.) by keeping directories only.
_bn_mounts_all() {
  awk '$3!~/^(proc|sysfs|tmpfs|devtmpfs|devpts|cgroup2?|mqueue|fuse\.lxcfs|fuse\.gvfsd-fuse|securityfs|debugfs|tracefs|pstore|bpf|autofs|hugetlbfs|configfs|fusectl|binfmt_misc|nsfs|rpc_pipefs|ramfs|squashfs|efivarfs|selinuxfs|nfsd|swap)$/ &&
    $2!~/^\/(proc|sys|dev|run|boot\/efi)(\/|$)/ {gsub(/\\040/," ",$2); if(!s[$2]++) print $2}' /proc/mounts 2>/dev/null |
    while IFS= read -r _m; do [ -d "$_m" ] && printf '%s\n' "$_m"; done
}
# Print the mounts the "mounts" item shows: BN_MOUNTS ("|"-separated) if set, otherwise
# everything from _bn_mounts_all, minus / while the "disk" item is also enabled.
_bn_mounts() {
  if [ -n "$BN_MOUNTS" ]; then printf '%s\n' "$BN_MOUNTS" | tr '|' '\n'; return 0; fi
  case " $BN_ITEMS " in *" disk "*) _sr=1 ;; *) _sr=0 ;; esac
  _bn_mounts_all | while IFS= read -r _m; do
    [ "$_sr" = 1 ] && [ "$_m" = / ] && continue
    printf '%s\n' "$_m"
  done
}
# awk prelude for `df -Pk` row 2: find the NN% column so filesystem names containing spaces still parse
_bn_dfc='NR==2{for(i=NF;i>4;i--)if($i~/^[0-9]+%$/)break;p=$i;sub("%","",p);t=$(i-3);u=$(i-2);a=$(i-1)}NR==2'
# Collect the live value for an item key. Sets _v (display text, "n/a" if unavailable)
# and _p (integer usage percent for bar/threshold items, empty otherwise).
# Every probe has fallbacks so it works on glibc, musl/busybox and minimal images.
_bn_val() {
  _v=''; _p=''
  case "$1" in
    hostname) _v=$(cat /proc/sys/kernel/hostname 2>/dev/null || hostname 2>/dev/null) ;;
    fqdn) _v=$(hostname -f 2>/dev/null) ;;
    ip)
      _v=$(ip -4 -o addr show scope global 2>/dev/null | awk '{split($4,a,"/");print a[1];exit}')
      [ -n "$_v" ] || _v=$(hostname -I 2>/dev/null | awk '{print $1}')
      [ -n "$_v" ] || _v=$(ifconfig 2>/dev/null | awk '/inet /&&$2!~/127\./{sub("addr:","",$2);print $2;exit}') ;;
    ipv6) _v=$(ip -6 -o addr show scope global 2>/dev/null | awk '{split($4,a,"/");print a[1];exit}') ;;
    os) _v=$([ -r /etc/os-release ] && . /etc/os-release; printf '%s' "${PRETTY_NAME:-${NAME:-$(uname -s)}}") ;;
    kernel) _v=$(uname -r) ;;
    arch) _v=$(uname -m) ;;
    uptime) _v=$(awk '{s=int($1);d=int(s/86400);h=int(s%86400/3600);m=int(s%3600/60);if(d)printf "%dd ",d;printf "%dh %dm",h,m}' /proc/uptime 2>/dev/null) ;;
    load) _v=$(cut -d' ' -f1-3 /proc/loadavg 2>/dev/null) ;;
    cores) _v=$(grep -c '^processor' /proc/cpuinfo 2>/dev/null) ;;
    cpu_model) _v=$(awk -F': *' '/^(model name|Hardware|cpu model)/{print $2;exit}' /proc/cpuinfo 2>/dev/null) ;;
    cpu)
      _a=$(awk '/^cpu /{print $2+$3+$4+$5+$6+$7+$8, $5+$6}' /proc/stat 2>/dev/null)
      sleep 0.2 2>/dev/null || sleep 1
      _b=$(awk '/^cpu /{print $2+$3+$4+$5+$6+$7+$8, $5+$6}' /proc/stat 2>/dev/null)
      _p=$(echo "$_a $_b" | awk 'NF==4{dt=$3-$1;di=$4-$2;printf "%d",(dt>0?(dt-di)*100/dt:0)}')
      _n=$(grep -c '^processor' /proc/cpuinfo 2>/dev/null)
      if [ "$_n" = 1 ]; then _u=core; else _u=cores; fi
      [ -n "$_p" ] && _v="$_p% of $_n $_u" ;;
    memory)
      set -- $(awk '/^MemTotal:/{t=$2}/^MemAvailable:/{a=$2}/^MemFree:/{f=$2}/^Buffers:/{b=$2}/^Cached:/{c=$2}
        END{if(!a)a=f+b+c;u=t-a;printf "%d %.1f %.1f",(t?u*100/t:0),u/1048576,t/1048576}' /proc/meminfo 2>/dev/null)
      [ $# -eq 3 ] && { _p=$1; _v="$2 / $3 GiB ($1%)"; } ;;
    swap)
      set -- $(awk '/^SwapTotal:/{t=$2}/^SwapFree:/{f=$2}END{u=t-f;printf "%d %.1f %.1f",(t?u*100/t:0),u/1048576,t/1048576}' /proc/meminfo 2>/dev/null)
      if [ "${3:-0.0}" = 0.0 ]; then _v='none'; else _p=$1; _v="$2 / $3 GiB ($1%)"; fi ;;
    disk)
      set -- $(df -Pk / 2>/dev/null | awk "$_bn_dfc"'{printf "%s %.1f %.1f",p,u/1048576,t/1048576}')
      [ $# -eq 3 ] && { _p=$1; _v="$2 / $3 GiB ($1%)"; } ;;
    mnt:*)
      _x=$(df -Pk "${1#mnt:}" 2>/dev/null | awk 'function h(k){return k>=1073741824?sprintf("%.1f TiB",k/1073741824):k>=1048576?sprintf("%.1f GiB",k/1048576):sprintf("%.0f MiB",k/1024)}
        '"$_bn_dfc"'{print p"|"h(a)"|"h(t)}')
      if [ -n "$_x" ]; then _p=${_x%%|*}; _x=${_x#*|}; _v="${_x%%|*} free of ${_x#*|}"; fi ;;
    procs) _v=$(ls -d /proc/[0-9]* 2>/dev/null | wc -l | tr -d ' ') ;;
    users) _v=$(who 2>/dev/null | wc -l | tr -d ' ') ;;
    date) _v=$(date '+%a %d %b %Y %H:%M') ;;
  esac
  case "$_p" in ''|*[!0-9]*) _p='' ;; esac
  [ -n "$_v" ] || _v='n/a'
}
# Set _bf and _be to the filled and empty parts of a usage bar for percentage $1: BN_BAR_W
# cells of BN_BAR_FULL then BN_BAR_EMPTY. They are colored separately so the track is dim.
_bn_bar() {
  _f=$(($1 * BN_BAR_W / 100))
  [ "$_f" -gt "$BN_BAR_W" ] && _f=$BN_BAR_W
  _bf=''; _be=''; _i=0
  while [ "$_i" -lt "$BN_BAR_W" ]; do
    if [ "$_i" -lt "$_f" ]; then _bf="$_bf$BN_BAR_FULL"; else _be="$_be$BN_BAR_EMPTY"; fi
    _i=$((_i + 1))
  done
}
# Build one formatted item into _cell: icon, padded label, separator, bar, value.
# $1 = item key (or mnt:<path>); $2 = list | pad (columns layout) | inline.
# Per-item value color BN_VC_<key> wins; mounts share the "mounts" key for color/icon.
# A bar shows when the item has a usage percentage and BN_B_<key> (or, if unset, BN_BAR)
# is "yes", so bars can be switched on or off for all items or one at a time. Load colors
# (BN_THRESH) color the bar; with no bar, the value keeps its usual color and only turns
# yellow or red at high usage, so switching a bar off doesn't change how the text looks.
_bn_cell() {
  case "$1" in mnt:*) _ck=mounts ;; *) _ck=$1 ;; esac
  _bn_val "$1"; _bn_label "$1"; _bn_icon "$_ck"
  eval "_vc=\${BN_VC_$_ck:-}; _bb=\${BN_B_$_ck:-\$BN_BAR}"
  _vcc=$_CV; [ -n "$_vc" ] && _vcc=$(_bn_c "$_vc")
  _bar=''
  if [ "$_bb" = yes ] && [ -n "$_p" ]; then
    _bn_bar "$_p"
    if [ "$BN_THRESH" = yes ]; then _bfc=$(_bn_thc "$_p"); else _bfc=$_vcc; fi
    _bar="$_bfc$_bf$_R$_CS$_be$_R "
  elif [ -n "$_p" ] && [ "$_p" -ge 60 ] && [ "$BN_THRESH" = yes ] && [ -z "$_vc" ]; then
    _vcc=$(_bn_thc "$_p")
  fi
  # Keep the columns layout aligned when some rows have a bar and this one doesn't
  if [ -z "$_bar" ] && [ "$2" = pad ] && [ "$BN_BAR" = yes ]; then
    _bar=$(printf "%$((BN_BAR_W + 1))s" '')
  fi
  if [ "$2" = inline ]; then _lt=$_l; else _lt=$(printf "%-${BN_LABEL_W}s" "$_l"); fi
  if [ "$2" = pad ]; then _vt=$(printf "%-${BN_VALUE_W}s" "$_v"); else _vt=$_v; fi
  _it=''; [ -n "$_ic" ] && _it="$_CI$_ic$_R "
  _cell="$_it$_CL$_lt$_R$_CS$BN_SEP$_R$_bar$_vcc$_vt$_R"
}
# Print one item according to BN_LAYOUT, tracking row state in _col (columns) / _inl (inline).
_bn_item() {
  case "$BN_LAYOUT" in
    columns)
      _bn_cell "$1" pad
      if [ "$_col" = 0 ]; then printf '%s%s' "$_ind" "$_cell"; _col=1; else printf '   %s\n' "$_cell"; _col=0; fi ;;
    inline)
      _bn_cell "$1" inline
      if [ "$_inl" = 0 ]; then printf '%s%s' "$_ind" "$_cell"; _inl=1; else printf '%s  |  %s%s' "$_CS" "$_R" "$_cell"; fi ;;
    *)
      _bn_cell "$1" list
      printf '%s%s\n' "$_ind" "$_cell" ;;
  esac
}
# Entry point: print the art (cycling BN_ART_COLOR per line for gradients), then each
# entry in BN_ITEMS in order. textN entries are full-width static lines; "mounts"
# expands to one row per mount; everything else is a normal item.
_bn_show() {
  _R=$(printf '\033[0m')
  _CL=$(_bn_c "$BN_C_LABEL"); _CV=$(_bn_c "$BN_C_VALUE"); _CS=$(_bn_c "$BN_C_SEP"); _CT=$(_bn_c "$BN_C_TEXT")
  _CI=$(_bn_c "${BN_C_ICON:-}")
  _ind=$(printf "%${BN_INDENT}s" '')
  if [ -n "$(_bn_art)" ]; then
    set -- $BN_ART_COLOR
    _bn_art | while IFS= read -r _line; do
      _c=${1:-}
      if [ $# -gt 1 ]; then shift; set -- "$@" "$_c"; fi
      printf '%s%s%s%s\n' "$_ind" "$(_bn_c "$_c")" "$_line" "$_R"
    done
    printf '\n'
  fi
  # Banner title and credits sit between the art and the info items, like the
  # community-scripts banner they can come from
  _tl=0
  if [ -n "${BN_TITLE:-}" ]; then
    printf '%s%s%s%s\n' "$_ind" "$(_bn_c "${BN_C_TITLE:-bold}")" "$BN_TITLE" "$_R"
    _tl=1
  fi
  if [ -n "${BN_CREDITS:-}" ] && [ "${BN_CREDITS_ON:-yes}" = yes ]; then
    printf '%s%s%s%s\n' "$_ind" "$_CT" "$BN_CREDITS" "$_R"
    _tl=1
  fi
  [ "$_tl" = 1 ] && printf '\n'
  _col=0; _inl=0
  for _k in $BN_ITEMS; do
    case "$_k" in
      text[0-9]*)
        [ "$_col" = 1 ] && printf '\n'
        [ "$_inl" = 1 ] && printf '\n'
        _col=0; _inl=0; _n=${_k#text}
        eval "_t=\${BN_TEXT_$_n:-}; _tc=\${BN_TC_$_n:-}"
        _tcc=$_CT; [ -n "$_tc" ] && _tcc=$(_bn_c "$_tc")
        printf '%s%s%s%s\n' "$_ind" "$_tcc" "$_t" "$_R" ;;
      mounts)
        _ifs=$IFS; IFS='
'
        for _m in $(_bn_mounts); do IFS=$_ifs; _bn_item "mnt:$_m"; done
        IFS=$_ifs ;;
      *) _bn_item "$_k" ;;
    esac
  done
  [ "$_col" = 1 ] && printf '\n'
  [ "$_inl" = 1 ] && printf '\n'
  printf '\n'
}
__BANNARR_RENDERER__
}
