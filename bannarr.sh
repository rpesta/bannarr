# Render $1 in the built-in 5x7 font into ART_LINES: half-block art 4 rows tall (7 pixel rows
# plus a blank one, two per line), with a 1-pixel gap between letters. Letters are uppercased
# and anything without a glyph becomes a space. art_scale can enlarge the result.
block_text() {
  local s=${1^^} ch i r
  local -a rows
  _PX=('' '' '' '' '' '' '' '')
  for ((i = 0; i < ${#s}; i++)); do
    ch=${s:i:1}
    [[ -n ${FONT[$ch]+x} ]] || ch=' '
    read -ra rows <<<"${FONT[$ch]}"
    for r in 0 1 2 3 4 5 6; do _PX[r]+="${rows[r]}."; done
    _PX[7]+='......'
  done
  mapfile -t ART_LINES < <(px_to_art 1)
}

