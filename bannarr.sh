# Rename $1 to $1.bannarr-disabled so nothing picks it up; the file itself is never edited.
# If a disabled copy already exists (the file was recreated since, e.g. by an installer),
# the newer one gets a timestamp suffix instead, so unpark still restores the original.
# Returns 1 if there was nothing to park.
park() {
  [[ -e $1 || -L $1 ]] || return 1
  if [[ -e $1.bannarr-disabled || -L $1.bannarr-disabled ]]; then
    mv "$1" "$1.bannarr-disabled.$(date +%Y%m%d-%H%M%S)"
  else
    mv "$1" "$1.bannarr-disabled"
  fi
}

# Undo park: rename $1.bannarr-disabled back to $1, unless $1 has been recreated meanwhile.
# Returns 1 if nothing was restored.
unpark() {
  [[ -e $1.bannarr-disabled || -L $1.bannarr-disabled ]] || return 1
  if [[ -e $1 || -L $1 ]]; then
    msg_warn "$1 already exists - left it and $1.bannarr-disabled as they are"
    return 1
  fi
  mv "$1.bannarr-disabled" "$1"
}

