}

# True while other login messages are quieted by Bannarr.
is_quiet() { [[ -f $QUIET_DIR/enabled ]]; }

# Print what else a login on this box can show, for the login-messages screen.
motd_sources() {
  local f n=0
  for f in "$ETC_DIR"/update-motd.d/*; do [[ -f $f && -x $f ]] && ((n++)); done
  printf '   • %s active scripts in %s/update-motd.d (Debian/Ubuntu dynamic MOTD)\n' "$n" "$ETC_DIR"
  if [[ -s $MOTD_FILE ]]; then
    printf '   • %s (%s lines)\n' "$MOTD_FILE" "$(wc -l <"$MOTD_FILE" | tr -d ' ')"
  else
    printf '   • %s: empty or missing\n' "$MOTD_FILE"
  fi
  n=$(find "$ETC_DIR/motd.d" -mindepth 1 -maxdepth 1 2>/dev/null | wc -l | tr -d ' ')
  printf '   • %s entries in %s/motd.d (e.g. the Cockpit hint on RHEL/Fedora)\n' "$n" "$ETC_DIR"
  printf '   • "Last login: ..." from sshd (PrintLastLog) - Bannarr leaves this alone\n'
}

# Quiet other login messages, recording every change in QUIET_DIR so unquiet_motd undoes
# exactly that and nothing else:
#   - executable update-motd.d scripts: chmod a-x (what community-scripts does too). Renaming
#     isn't safe there, because run-parts --lsbsysinit still runs some dotted names.
#   - /etc/motd: parked as motd.bannarr-disabled
#   - /etc/motd.d/*: moved into QUIET_DIR/motd.d, because pam_motd shows every file in that
#     directory whatever its name
# Safe to re-run: save_apply calls it again to catch scripts a package upgrade re-enabled.
# $1 = "auto" to stay silent when there was nothing to change.
quiet_motd() {
  local f n=0
  mkdir -p "$QUIET_DIR/motd.d"
  touch "$QUIET_DIR/enabled"
  for f in "$ETC_DIR"/update-motd.d/*; do
    [[ -f $f && -x $f ]] || continue
    printf '%s %s\n' "$(stat -c %a "$f")" "${f##*/}" >>"$QUIET_DIR/update-motd.d.list"
    chmod a-x "$f" && ((n++))
  done
  park "$MOTD_FILE" && ((n++))
  for f in "$ETC_DIR"/motd.d/*; do
    [[ -e $f || -L $f ]] || continue
    if [[ -e $QUIET_DIR/motd.d/${f##*/} || -L $QUIET_DIR/motd.d/${f##*/} ]]; then
      mv "$f" "$QUIET_DIR/motd.d/${f##*/}.$(date +%Y%m%d-%H%M%S)"
    else
      mv "$f" "$QUIET_DIR/motd.d/"
    fi
    ((n++))
  done
  if ((n)) || [[ ${1:-} != auto ]]; then
    msg_ok "Quieted other login messages ($n change(s), all recorded in $QUIET_DIR)"
  fi
}

# Undo quiet_motd: restore recorded script modes, unpark /etc/motd and move /etc/motd.d
# entries back. Anything that can't go back (a newer file now has its name) stays in
# QUIET_DIR, so nothing is lost.
unquiet_motd() {
  local mode name f
  is_quiet || return 0
  if [[ -f $QUIET_DIR/update-motd.d.list ]]; then
    while read -r mode name; do
      f="$ETC_DIR/update-motd.d/$name"
      [[ -f $f ]] && chmod "$mode" "$f"
    done <"$QUIET_DIR/update-motd.d.list"
    rm -f "$QUIET_DIR/update-motd.d.list"
  fi
  unpark "$MOTD_FILE"
  for f in "$QUIET_DIR"/motd.d/*; do
    [[ -e $f || -L $f ]] || continue
    if [[ -e $ETC_DIR/motd.d/${f##*/} || -L $ETC_DIR/motd.d/${f##*/} ]]; then
      msg_warn "$ETC_DIR/motd.d/${f##*/} already exists - kept Bannarr's copy in $QUIET_DIR/motd.d"
    else
      mkdir -p "$ETC_DIR/motd.d"
      mv "$f" "$ETC_DIR/motd.d/"
    fi
  done
  rm -f "$QUIET_DIR/enabled"
  rmdir "$QUIET_DIR/motd.d" "$QUIET_DIR" 2>/dev/null
  msg_ok "Other login messages are back"
}

# Login-messages screen: explain what quieting changes, then toggle it.
motd_menu() {
  local r
  draw "Other login messages"
  echo "  Besides this banner, a login on this box can show:"
  motd_sources
  echo
  if is_quiet; then
    read -rp "  They are quiet now. Show them again (undoes exactly what Bannarr changed)? [y/N]: " r
    [[ $r =~ ^[yY] ]] && unquiet_motd
  else
    echo "  Quieting removes the execute bit from update-motd.d scripts, renames /etc/motd and"
    echo "  moves /etc/motd.d entries aside. Every change is recorded and can be undone here,"
    echo "  with --restore-motd, or by reverting to the default banner."
    read -rp "  Quiet them now? [y/N]: " r
    [[ $r =~ ^[yY] ]] && quiet_motd
  fi
  pause
}

# Write settings, art and BANNER_FILE, then disable the community-scripts banner. The new
# banner must pass "sh -n" before anything changes. A backup is never made here; the editor
# asks first (save_menu, ask_backup).
save_apply() {
  if [[ ! -d $PROFILE_DIR ]]; then
    msg_error "$PROFILE_DIR doesn't exist - this system doesn't run profile.d scripts at login"
    return 1
  fi
  build_profile >"$BANNER_FILE.new"
  if ! sh -n "$BANNER_FILE.new"; then
    rm -f "$BANNER_FILE.new"
    msg_error "Generated banner failed a syntax check - nothing was changed"
    return 1
  fi
  mkdir -p "$CONF_DIR"
  write_conf >"$CONF_FILE"
  chmod 600 "$CONF_FILE"
  if ((${#ART_LINES[@]})); then printf '%s\n' "${ART_LINES[@]}" >"$ART_FILE"; else : >"$ART_FILE"; fi
  disable_cs_banner
  if ((QUIET_ON_SAVE)); then
    quiet_motd
    QUIET_ON_SAVE=0
  elif is_quiet; then
    quiet_motd auto
  fi
  mv "$BANNER_FILE.new" "$BANNER_FILE"
  # Executable as well as readable: openSUSE's /etc/bash.bashrc only loads profile.d scripts
  # that pass [ -x ] (community-scripts marks its banner +x for the same reason)
  chmod 755 "$BANNER_FILE"
  DIRTY=0
  msg_ok "Banner saved to $BANNER_FILE - it shows on your next login"
  printf '   To go back to the original banner: %s\n' "$(run_cmd --revert)"
}

# Offer to back up the saved banner that is about to be replaced, then say where the backup
# is and the command that restores it. Only asked when there is a saved banner: the very first
# save replaces nothing of Bannarr's (an original community-scripts banner is kept by renaming).
ask_backup() {
  local r note=''
  [[ -f $CONF_FILE ]] || return 0
  has_backup && note=' This replaces your previous backup.'
  read -rp "  Back up your current banner first?$note [y/N]: " r
  [[ $r =~ ^[yY] ]] || return 0
  make_backup || return 0
  msg_ok "Backed up your current banner to $BACKUP_DIR"
  printf '   To restore it: %s\n' "$(run_cmd --restore)"
}

# Main menu "s": only with unsaved changes, pick Save or Cancel, then offer a backup of the
# banner being replaced, then apply.
save_menu() {
  if ((!DIRTY)); then
    draw
    msg_warn "No changes to save"
    pause
    return
  fi
  MENU=("s|Save" "c|Cancel")
  menu_pick "Save your changes to the login banner?"
  if [[ $PICK != s ]]; then
    msg_warn "Not saved - your changes are still here"
    pause
    return
  fi
  ask_backup
  save_apply
  pause
}

# True when the single backup exists.
has_backup() { [[ -f $BACKUP_DIR/bannarr.conf ]]; }

# Copy the saved settings and art into the single backup slot, BACKUP_DIR, replacing whatever
# was there. Bannarr deliberately keeps one backup only, not a library of designs.
make_backup() {
  [[ -f $CONF_FILE ]] || return 1
  mkdir -p "$BACKUP_DIR"
  cp -p "$CONF_FILE" "$BACKUP_DIR/bannarr.conf"
  if [[ -f $ART_FILE ]]; then cp -p "$ART_FILE" "$BACKUP_DIR/banner.txt"; else rm -f "$BACKUP_DIR/banner.txt"; fi
}

# Apply the backup as the banner, without questions. The backup itself stays, so restoring
# can be repeated.
restore_backup() {
  if ! has_backup; then
    msg_error "There is no backup to restore. Bannarr offers to make one when you save over a banner."
    return 1
  fi
  load_state "$BACKUP_DIR"
  save_apply
}

# Undo everything Bannarr changed on the system: remove its banner, bring back the
# community-scripts banner on community-scripts boxes, and show other login messages again
# if they were quieted. Settings and the backup are kept so --apply can turn it all back on.
revert_default() {
  if [[ -f $BANNER_FILE ]] && grep -q "$MARKER" "$BANNER_FILE"; then
    rm -f "$BANNER_FILE"
    msg_ok "Removed $BANNER_FILE"
  fi
  unpark "$CS_FILE" && msg_ok "Re-enabled the community-scripts banner"
  unquiet_motd
  msg_ok "Default login restored - it shows on your next login"
}

# Revert to the default banner, then optionally delete Bannarr's settings and backup. Anything
# unquiet_motd couldn't put back stays in QUIET_DIR, so that folder is never deleted.
uninstall() {
  local r
  revert_default
  read -rp "  Also delete Bannarr's settings and backup in $CONF_DIR? [y/N]: " r
  if [[ $r =~ ^[yY] ]]; then
    find "$CONF_DIR" -mindepth 1 -maxdepth 1 ! -name quiet -exec rm -rf {} +
    rmdir "$CONF_DIR" 2>/dev/null
    msg_ok "Removed Bannarr's settings and backup"
    [[ -d $QUIET_DIR ]] && msg_warn "Kept $QUIET_DIR - it holds login messages that couldn't be moved back"
  fi
  return 0
}

# Print a one-line summary of which banners are active.
banner_status() {
  if [[ -f $BANNER_FILE ]]; then
    printf '%sBannarr banner on%s' "$GN" "$CL"
  else
    printf '%sBannarr banner off%s' "$YW" "$CL"
  fi
  if [[ -f $CS_FILE ]]; then
    printf ' · community-scripts banner %son%s' "$YW" "$CL"
  elif [[ -f $CS_DISABLED ]]; then
    printf ' · community-scripts banner disabled (restorable)'
  fi
  is_quiet && printf ' · other login messages quiet'
  return 0
}

pause() { read -rp "  Press Enter to continue " _; }

# Restore submenu: bring back the backup, go back to the original banner, or uninstall.
restore_menu() {
  local r when
  while true; do
    MENU=()
    if has_backup; then
      when=$(date -r "$BACKUP_DIR/bannarr.conf" '+%Y-%m-%d %H:%M' 2>/dev/null)
      MENU+=("1|1) Restore the backup from ${when:-an earlier save}")
    else
      MENU+=("|   No backup yet: Bannarr offers one when you save over a banner")
    fi
    MENU+=("2|2) Go back to the original banner (turns Bannarr off; your design is kept)"
      "3|3) Uninstall Bannarr (go back, then optionally delete Bannarr's settings)")
    menu_pick "Restore - $(banner_status)"
    case $PICK in
      1)
        load_state "$BACKUP_DIR"
        DIRTY=1
        MENU=("s|Save it as your banner" "c|Cancel")
        menu_pick "Previewing the backup"
        if [[ $PICK == s ]]; then
          save_apply
        else
          load_state
          DIRTY=0
          msg_warn "Not restored - your banner is unchanged"
        fi
        pause
        ;;
      2)
        read -rp "  Turn Bannarr off and bring back the original banner? [y/N]: " r
        [[ $r =~ ^[yY] ]] && revert_default
        pause
        ;;
      3) uninstall; load_state; DIRTY=0; pause ;;
      '') return ;;
    esac
  done
}

# Banner title submenu: edit the title (the field starts with the current one), color it,
# remove it, and show or hide the community-scripts credits when this box has them.
title_menu() {
  local t last=''
  while true; do
    MENU=("1|1) Edit title: ${BN_TITLE:-(none)}"
      "2|2) Title color: $(swatch "${BN_C_TITLE:-}") ${BN_C_TITLE:-}"
      "3|3) Remove title")
    [[ -n ${BN_CREDITS:-} ]] && MENU+=("4|4) Credits: $([[ ${BN_CREDITS_ON:-yes} == yes ]] && echo shown || echo hidden)")
    menu_pick "Banner title - shown under the art" "$last"
    last=$PICK
    case $PICK in
      1)
        read -e -r -i "${BN_TITLE:-}" -p "  Title: " t
        BN_TITLE=$t
        DIRTY=1
        ;;
      2) pick_color BN_C_TITLE ;;
      3) BN_TITLE='' DIRTY=1 ;;
      4)
        if [[ ${BN_CREDITS_ON:-yes} == yes ]]; then BN_CREDITS_ON=no; else BN_CREDITS_ON=yes; fi
        DIRTY=1
        ;;
      '') return ;;
    esac
  done
}

# Top-level menu loop.
main_menu() {
  local r last=''
  while true; do
    MENU=("1|1) Banner art" "2|2) Banner title: ${BN_TITLE:-(none)}" "3|3) Info items"
      "4|4) Static text" "5|5) Layout & style" "6|6) Colors"
      "7|7) Other login messages: $(is_quiet && echo quiet || echo shown)"
      "s|s) Save" "r|r) Restore" "q|q) Quit")
    menu_pick "Main menu" "$last"
    last=$PICK
    case $PICK in
      1) art_menu ;;
      2) title_menu ;;
      3) items_menu ;;
      4) text_menu ;;
      5) style_menu ;;
      6) colors_menu ;;
      7) motd_menu ;;
      s) save_menu ;;
      r) restore_menu ;;
      q | '')
        if ((DIRTY)); then
          read -rp "  Discard unsaved changes? [y/N]: " r
          [[ $r =~ ^[yY] ]] || continue
        fi
        printf '\033[H\033[2J'
        exit 0
        ;;
    esac
  done
}

# Print command-line help, under the wordmark when output is a wide enough terminal.
usage() {
  [[ -t 1 ]] && (($(tput cols 2>/dev/null || echo 80) >= LOGO_WIDTH + 4)) && print_logo
  cat <<EOF
Bannarr - customise the login banner on any Linux box ($BANNER_FILE)

  bannarr.sh                    interactive editor with live preview
  bannarr.sh --preview          print the banner from the saved settings
  bannarr.sh --apply            build and install the banner from saved settings
                                (also re-disables a recreated community-scripts banner)
  bannarr.sh --restore          bring back the banner you backed up when you last saved
  bannarr.sh --quiet-motd       quiet other login messages (/etc/motd, update-motd.d, motd.d)
  bannarr.sh --restore-motd     show them again, undoing exactly what --quiet-motd changed
  bannarr.sh --revert           turn Bannarr off and bring back the original banner
                                (and other login messages, if they were quieted)
  bannarr.sh --uninstall        revert, then optionally delete Bannarr's settings
EOF
}

# Exit unless running as root (skipped when BANNARR_ETC_DIR or BANNARR_DIR redirect writes
# somewhere else for testing).
need_root() {
  if [[ $EUID -ne 0 && -z ${BANNARR_ETC_DIR:-}${BANNARR_DIR:-} ]]; then
    msg_error "Bannarr needs root to write $BANNER_FILE - run it with sudo or as root"
    exit 1
  fi
}

# First run on a community-scripts container (no saved design yet). set_defaults has taken the
# original banner's Banner Title ("<App> LXC Container") and Credits ("Provided by:
# community-scripts ORG ...") into BN_TITLE and BN_CREDITS. Show both in a checklist, checked
# (kept); unchecking removes one, and the preview follows. Then ask whether to also hide the
# plain copy of the title and OS that community-scripts writes to /etc/motd.
first_run_cs() {
  [[ -f $CONF_FILE ]] && return 0
  is_cs_box || return 0
  _FR_TITLE=$BN_TITLE
  MENU=()
  declare -gA CHECKED=()
  if [[ -n $BN_TITLE ]]; then
    MENU+=("title|Banner Title   $BN_TITLE")
    CHECKED[title]=1
  fi
  if [[ -n $BN_CREDITS ]]; then
    MENU+=("credits|Credits        $BN_CREDITS")
    CHECKED[credits]=1
  fi
  if ((${#MENU[@]})); then
    MENU_NOTE="Its banner has these parts. Uncheck any you want to remove (you can change them later in the menu)."
    MENU_ON_TOGGLE=_first_run_toggle
    menu_check "community-scripts container detected" || { CHECKED[title]=1 CHECKED[credits]=1; }
    MENU_NOTE='' MENU_ON_TOGGLE=''
    _first_run_toggle
  fi
  # community-scripts also writes a plain copy of the title and OS to /etc/motd, which login
  # prints above any profile.d banner. Offer to hide it with the usual, exactly reversible
  # quiet mode, applied on save like every other change.
  if [[ -f $MOTD_FILE ]] && grep -q 'LXC Container' "$MOTD_FILE" && ! is_quiet; then
    MENU=("h|Hide it" "k|Keep it")
    menu_pick "Also hide the plain copy of the title and OS that community-scripts prints above the banner?"
    [[ $PICK == h ]] && QUIET_ON_SAVE=1
  fi
  return 0
}

# MENU_ON_TOGGLE hook for first_run_cs: apply the checkboxes to the design.
_first_run_toggle() {
  if [[ -n ${CHECKED[title]+x} ]]; then BN_TITLE=$_FR_TITLE; else BN_TITLE=''; fi
  if [[ -n ${CHECKED[credits]+x} ]]; then BN_CREDITS_ON=yes; else BN_CREDITS_ON=no; fi
}

# Parse arguments, then start the interactive editor.
main() {
  case "${1:-}" in
    -h | --help) usage; exit 0 ;;
    --preview) load_state; build_profile preview >"$TMP"; sh "$TMP"; exit 0 ;;
    --apply) need_root; load_state; save_apply; exit $? ;;
    --restore) need_root; restore_backup; exit $? ;;
    --quiet-motd) need_root; quiet_motd; exit 0 ;;
    --restore-motd)
      need_root
      is_quiet || { msg_warn "Other login messages aren't quieted - nothing to restore"; exit 0; }
      unquiet_motd
      exit 0
      ;;
    --revert) need_root; revert_default; exit 0 ;;
    --uninstall) need_root; uninstall; exit 0 ;;
    '') ;;
    *) usage; exit 1 ;;
  esac
  need_root
  load_state
  first_run_cs
  main_menu
}

main "$@"
